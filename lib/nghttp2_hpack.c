static const nghttp2_hpack_nv *
hpack_context_get_table_entry(const nghttp2_hpack_context *ctx, size_t idx) {
  if (idx == 0) {
    return NULL;
  }

  --idx;

  if (!INDEX_RANGE_VALID(ctx, idx)) {
    return NULL;
  }

  return nghttp2_hpack_context_table_get(ctx, idx);
}

