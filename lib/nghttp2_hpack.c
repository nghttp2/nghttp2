void nghttp2_hpack_read_state_free(nghttp2_hpack_read_state *rstate) {
  nghttp2_rcbuf_decref(rstate->value);
  nghttp2_rcbuf_decref(rstate->name);
}

void nghttp2_hpack_read_state_reset(nghttp2_hpack_read_state *rstate) {
  rstate->name = NULL;
  rstate->value = NULL;
  nghttp2_buf_init(&rstate->namebuf);
  nghttp2_buf_init(&rstate->valuebuf);
  rstate->left = 0;
  rstate->prefix = 0;
  rstate->index = 0;
  rstate->never = 0;
  rstate->indexing = 0;
  rstate->huffman_encoded = 0;
}
